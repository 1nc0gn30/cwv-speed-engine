def generate_apache_htaccess(custom_rules: Optional[List[Dict[str, Any]]] = None) -> str:
    """Generate Apache `.htaccess` speed and caching configuration."""
    lines = [
        "# ==========================================================================",
        "# Apache .htaccess CWV Optimization (Generated by CWV Speed Engine)",
        "# ==========================================================================",
        "",
        "# 1. Gzip Compression (mod_deflate)",
        "<IfModule mod_deflate.c>",
        "    AddOutputFilterByType DEFLATE text/html text/plain text/xml text/css",
        "    AddOutputFilterByType DEFLATE application/javascript application/json application/xml",
        "    AddOutputFilterByType DEFLATE image/svg+xml image/x-icon font/woff font/woff2",
        "</IfModule>",
        "",
        "# 2. Browser Expires Headers (mod_expires)",
        "<IfModule mod_expires.c>",
        "    ExpiresActive On",
        "    ExpiresDefault \"access plus 1 month\"",
        "    ExpiresByType text/html \"access plus 0 seconds\"",
        "    ExpiresByType application/javascript \"access plus 1 year\"",
        "    ExpiresByType text/css \"access plus 1 year\"",
        "    ExpiresByType font/woff2 \"access plus 1 year\"",
        "    ExpiresByType image/webp \"access plus 1 year\"",
        "    ExpiresByType image/avif \"access plus 1 year\"",
        "</IfModule>",
        "",
        "# 3. Cache-Control & Security Headers (mod_headers)",
        "<IfModule mod_headers.c>",
        "    # Static Assets",
        "    <FilesMatch \"\\.(ico|pdf|flv|jpg|jpeg|png|gif|webp|avif|js|css|swf|woff|woff2|ttf|eot)$\">",
        f"        Header set Cache-Control \"{HEADER_IMMUTABLE_STATIC}\"",
        "    </FilesMatch>",
        "",
        "    # Service Worker",
        "    <FilesMatch \"^(sw|service-worker)\\.js$\">",
        f"        Header set Cache-Control \"{HEADER_SERVICE_WORKER}\"",
        "    </FilesMatch>",
        "",
        "    # HTML Pages",
        "    <FilesMatch \"\\.(html|htm)$\">",
        f"        Header set Cache-Control \"{HEADER_HTML_REVALIDATE}\"",
        "    </FilesMatch>",
        "</IfModule>",
        "",
    ]
    return "\n".join(lines)


