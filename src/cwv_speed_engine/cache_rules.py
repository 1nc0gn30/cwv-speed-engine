def generate_cache_headers(
    framework_or_server: str = "netlify",
    custom_rules: Optional[List[Dict[str, Any]]] = None,
) -> Dict[str, Any]:
    """Generate full caching configuration for the requested hosting framework or web server.

    Args:
        framework_or_server: Target framework ('netlify', 'vercel', 'nginx', 'cloudflare', 'nextjs', 'apache').
        custom_rules: Optional list of custom path and header rules.

    Returns:
        Dict with framework name, recommended filename, content, and description.
    """
    key = framework_or_server.lower().strip()
    generator = FRAMEWORK_GENERATORS.get(key, generate_netlify_headers)
    filename = DEFAULT_FILENAMES.get(key, "_headers")

    content = generator(custom_rules=custom_rules)

    return {
        "framework": key,
        "default_filename": filename,
        "content": content,
        "static_cache_control": HEADER_IMMUTABLE_STATIC,
        "html_cache_control": HEADER_HTML_REVALIDATE,
    }


def export_cache_config(
    target: str = "netlify",
    output_path: Optional[Union[str, Path]] = None,
    custom_rules: Optional[List[Dict[str, Any]]] = None,
) -> Dict[str, Any]:
    """Generate and optionally write cache configuration to disk atomically.

    Args:
        target: Target server or hosting platform.
        output_path: Destination file path. If omitted, uses default filename.
        custom_rules: Optional custom header rules.

    Returns:
        Dict with destination path, content, and write status.
    """
    result = generate_cache_headers(framework_or_server=target, custom_rules=custom_rules)
    dest_path = resolve_path(output_path) if output_path else Path(result["default_filename"]).resolve()

    written_path = atomic_write_text(dest_path, result["content"])

    return {
        "framework": result["framework"],
        "path": str(written_path),
        "content": result["content"],
        "written": True,
    }
