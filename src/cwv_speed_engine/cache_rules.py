"""Cache-Control Rule Generator and Multi-Platform Exporters.

Generates production-grade caching and compression configuration for:
  - Netlify (_headers, netlify.toml)
  - Vercel (vercel.json)
  - Nginx (nginx.conf with Gzip & Brotli)
  - Cloudflare Pages / Workers (_headers, worker.js)
  - Next.js (next.config.js async headers)
  - Apache (.htaccess with mod_headers, mod_expires, mod_deflate)

Zero external runtime dependencies - pure Python stdlib.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Dict, List, Optional, Union

from .compat import atomic_write_text, resolve_path


# Default rule blueprints
